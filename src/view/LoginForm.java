    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword()).trim();

        // Basic validation
        if (username.isEmpty() || password.isEmpty()) {
            lblError.setText("Username dan password tidak boleh kosong!");
            return;
        }

        // Check database
        try {
            Connection con = DBConnection.getConnection();
            String sql = "SELECT * FROM karyawan WHERE username=? AND password=?";
            PreparedStatement ps = con.prepareStatement(sql);
            ps.setString(1, username);
            ps.setString(2, password);
            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                String jabatan = rs.getString("jabatan");
                String namaKaryawan = rs.getString("nama");

                // Save session
                SessionManager.setUsername(username);
                SessionManager.setNama(namaKaryawan);
                SessionManager.setJabatan(jabatan);

                // Close login, open dashboard
                this.dispose();
                new DashboardForm().setVisible(true);

            } else {
                lblError.setText("Username atau password salah!");
                txtPassword.setText("");
            }

            rs.close();
            ps.close();
            con.close();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                "Gagal koneksi ke database!\n" + e.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnLoginActionPerformed

