    private void setupTable() {
        tableModel = new DefaultTableModel(
            new String[]{"ID", "Nama", "Alamat", "No HP", "Email", "Username"}, 0
        ) {
            public boolean isCellEditable(int row, int col) {
                return false;
            }
        };
        tblTamu.setModel(tableModel);
        tblTamu.getColumnModel().getColumn(0).setMinWidth(0);
        tblTamu.getColumnModel().getColumn(0).setMaxWidth(0); // hide ID column
        tblTamu.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);

        // When user clicks a row, fill the form fields
        tblTamu.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                fillFormFromTable();
            }
        });
    }
    private void loadData() {
        loadDataWithFilter("");
    }
    private void loadDataWithFilter(String keyword) {
        tableModel.setRowCount(0);
        try {
            Connection con = DBConnection.getConnection();
            String sql = "SELECT * FROM tamu WHERE nama LIKE ? OR email LIKE ? OR noHP LIKE ? ORDER BY nama";
            PreparedStatement ps = con.prepareStatement(sql);
            ps.setString(1, "%" + keyword + "%");
            ps.setString(2, "%" + keyword + "%");
            ps.setString(3, "%" + keyword + "%");
            ResultSet rs = ps.executeQuery();

            while (rs.next()) {
                tableModel.addRow(new Object[]{
                    rs.getInt("idTamu"),
                    rs.getString("nama"),
                    rs.getString("alamat"),
                    rs.getString("noHP"),
                    rs.getString("email"),
                    rs.getString("username")
                });
            }

            rs.close();
            ps.close();
            con.close();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                "Gagal memuat data!\n" + e.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    private void fillFormFromTable() {
        int row = tblTamu.getSelectedRow();
        if (row == -1) return;

        txtNama.setText(tableModel.getValueAt(row, 1).toString());
        txtAlamat.setText(tableModel.getValueAt(row, 2).toString());
        txtNoHP.setText(tableModel.getValueAt(row, 3).toString());
        txtEmail.setText(tableModel.getValueAt(row, 4).toString());
        txtUsername.setText(tableModel.getValueAt(row, 5).toString());
        txtPassword.setText(""); // never show password
    }
    private boolean validateInput() {
        if (txtNama.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama tidak boleh kosong!");
            return false;
        }
        if (txtNoHP.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "No HP tidak boleh kosong!");
            return false;
        }
        if (txtEmail.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Email tidak boleh kosong!");
            return false;
        }
        if (txtUsername.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Username tidak boleh kosong!");
            return false;
        }
        // Validate email format
        if (!txtEmail.getText().trim().matches("^[\\w.-]+@[\\w.-]+\\.[a-zA-Z]{2,}$")) {
            JOptionPane.showMessageDialog(this, "Format email tidak valid!");
            return false;
        }
        return true;
    }

