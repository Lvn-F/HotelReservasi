    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        if (!validateInput()) return;

        // Password is required for new tamu
        if (new String(txtPassword.getPassword()).trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Password tidak boleh kosong!");
            return;
        }

        try {
            Connection con = DBConnection.getConnection();

            // Check if username already exists
            PreparedStatement check = con.prepareStatement(
                "SELECT idTamu FROM tamu WHERE username=?");
            check.setString(1, txtUsername.getText().trim());
            ResultSet rs = check.executeQuery();
            if (rs.next()) {
                JOptionPane.showMessageDialog(this, "Username sudah digunakan!");
                rs.close();
                check.close();
                con.close();
                return;
            }
            rs.close();
            check.close();

            // Insert new tamu
            String sql = "INSERT INTO tamu (nama, alamat, noHP, email, username, password) VALUES (?,?,?,?,?,?)";
            PreparedStatement ps = con.prepareStatement(sql);
            ps.setString(1, txtNama.getText().trim());
            ps.setString(2, txtAlamat.getText().trim());
            ps.setString(3, txtNoHP.getText().trim());
            ps.setString(4, txtEmail.getText().trim());
            ps.setString(5, txtUsername.getText().trim());
            ps.setString(6, new String(txtPassword.getPassword()).trim());
            ps.executeUpdate();

            JOptionPane.showMessageDialog(this, "Tamu berhasil ditambahkan!");
            clearForm();
            loadData();

            ps.close();
            con.close();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                "Gagal menambahkan tamu!\n" + e.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        int row = tblTamu.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Pilih tamu yang ingin diedit!");
            return;
        }
        if (!validateInput()) return;

        int idTamu = (int) tableModel.getValueAt(row, 0);
        String newPassword = new String(txtPassword.getPassword()).trim();

        try {
            Connection con = DBConnection.getConnection();
            PreparedStatement ps;

            // If password field is filled, update password too
            if (!newPassword.isEmpty()) {
                String sql = "UPDATE tamu SET nama=?, alamat=?, noHP=?, email=?, username=?, password=? WHERE idTamu=?";
                ps = con.prepareStatement(sql);
                ps.setString(1, txtNama.getText().trim());
                ps.setString(2, txtAlamat.getText().trim());
                ps.setString(3, txtNoHP.getText().trim());
                ps.setString(4, txtEmail.getText().trim());
                ps.setString(5, txtUsername.getText().trim());
                ps.setString(6, newPassword);
                ps.setInt(7, idTamu);
            } else {
                // Don't update password if field is empty
                String sql = "UPDATE tamu SET nama=?, alamat=?, noHP=?, email=?, username=? WHERE idTamu=?";
                ps = con.prepareStatement(sql);
                ps.setString(1, txtNama.getText().trim());
                ps.setString(2, txtAlamat.getText().trim());
                ps.setString(3, txtNoHP.getText().trim());
                ps.setString(4, txtEmail.getText().trim());
                ps.setString(5, txtUsername.getText().trim());
                ps.setInt(6, idTamu);
            }

            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Data tamu berhasil diupdate!");
            clearForm();
            loadData();

            ps.close();
            con.close();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                "Gagal mengupdate tamu!\n" + e.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        int row = tblTamu.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Pilih tamu yang ingin dihapus!");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Yakin ingin menghapus tamu ini?\nData reservasi terkait juga akan terpengaruh!",
            "Konfirmasi Hapus",
            JOptionPane.YES_NO_OPTION
        );

        if (confirm == JOptionPane.YES_OPTION) {
            int idTamu = (int) tableModel.getValueAt(row, 0);
            try {
                Connection con = DBConnection.getConnection();
                PreparedStatement ps = con.prepareStatement(
                    "DELETE FROM tamu WHERE idTamu=?");
                ps.setInt(1, idTamu);
                ps.executeUpdate();

                JOptionPane.showMessageDialog(this, "Tamu berhasil dihapus!");
                clearForm();
                loadData();

                ps.close();
                con.close();

            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this,
                    "Gagal menghapus tamu!\n" + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnHapusActionPerformed

