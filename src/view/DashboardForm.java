    private void applyRoleAccess() {
        String jabatan = SessionManager.getJabatan();
        
        if (jabatan.equals("AdminManager")) {
            // Admin can see everything
            btnKamar.setEnabled(true);
            btnTamu.setEnabled(true);
            btnReservasi.setEnabled(true);
            btnPembayaran.setEnabled(true);
            btnInvoice.setEnabled(true);
            btnLaporan.setEnabled(true); // only admin sees this
            
        } else if (jabatan.equals("Resepsionis")) {
            // Resepsionis cannot access Laporan and Kamar management
            btnKamar.setEnabled(false);
            btnLaporan.setEnabled(false);
            btnTamu.setEnabled(true);
            btnReservasi.setEnabled(true);
            btnPembayaran.setEnabled(true);
            btnInvoice.setEnabled(true);
        }
    }
    


