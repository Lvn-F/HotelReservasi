    private void exportToCSV(DefaultTableModel model, String filename) {
        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this,
                "Tidak ada data untuk diexport!");
            return;
        }

        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setSelectedFile(new File(filename));
        int result = fileChooser.showSaveDialog(this);

        if (result == JFileChooser.APPROVE_OPTION) {
            File file = fileChooser.getSelectedFile();
            // Add .csv extension if not present
            if (!file.getName().endsWith(".csv")) {
                file = new File(file.getAbsolutePath() + ".csv");
            }

            try (PrintWriter pw = new PrintWriter(
                    new FileWriter(file))) {
                // Write header
                StringBuilder header = new StringBuilder();
                for (int i = 0; i < model.getColumnCount(); i++) {
                    header.append(model.getColumnName(i));
                    if (i < model.getColumnCount() - 1)
                        header.append(",");
                }
                pw.println(header);

                // Write rows
                for (int row = 0; row < model.getRowCount(); row++) {
                    StringBuilder line = new StringBuilder();
                    for (int col = 0; col < model.getColumnCount(); col++) {
                        line.append(model.getValueAt(row, col));
                        if (col < model.getColumnCount() - 1)
                            line.append(",");
                    }
                    pw.println(line);
                }

                JOptionPane.showMessageDialog(this,
                    "Export berhasil!\n" + file.getAbsolutePath());

            } catch (IOException e) {
                JOptionPane.showMessageDialog(this,
                    "Gagal export!\n" + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }

