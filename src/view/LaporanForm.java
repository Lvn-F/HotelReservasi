    private void btnCariReservasiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCariReservasiActionPerformed
        String dari = txtDariTgl.getText().trim();
        String sampai = txtSampaiTgl.getText().trim();

        if (dari.isEmpty() || sampai.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Tanggal tidak boleh kosong! (Format: yyyy-MM-dd)");
            return;
        }

        tableModelReservasi.setRowCount(0);
        try {
            Connection con = DBConnection.getConnection();

            // Build query based on status filter
            String statusFilter = cmbStatusFilter.getSelectedItem().toString();
            String sql =
                "SELECT t.nama, k.noKamar, k.tipeKamar, " +
                "r.tglCheckIn, r.tglCheckOut, " +
                "r.TotalHarga, r.status " +
                "FROM reservasi r " +
                "JOIN tamu t ON r.idTamu = t.idTamu " +
                "JOIN kamar k ON r.idKamar = k.idKamar " +
                "WHERE r.tglCheckIn BETWEEN ? AND ? ";

            if (!statusFilter.equals("Semua")) {
                sql += "AND r.status = ? ";
            }
            sql += "ORDER BY r.tglCheckIn ASC";

            PreparedStatement ps = con.prepareStatement(sql);
            ps.setString(1, dari);
            ps.setString(2, sampai);
            if (!statusFilter.equals("Semua")) {
                ps.setString(3, statusFilter);
            }

            ResultSet rs = ps.executeQuery();
            int no = 1;
            while (rs.next()) {
                tableModelReservasi.addRow(new Object[]{
                    no++,
                    rs.getString("nama"),
                    rs.getString("noKamar"),
                    rs.getString("tipeKamar"),
                    rs.getString("tglCheckIn"),
                    rs.getString("tglCheckOut"),
                    rs.getDouble("TotalHarga"),
                    rs.getString("status")
                });
            }

            lblTotalReservasi.setText(
                "Total: " + tableModelReservasi.getRowCount() + " reservasi");

            rs.close();
            ps.close();
            con.close();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                "Gagal memuat laporan!\n" + e.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCariReservasiActionPerformed

    private void btnCariPendapatanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCariPendapatanActionPerformed
        String dari = txtDariTglPendapatan.getText().trim();
        String sampai = txtSampaiTglPendapatan.getText().trim();

        if (dari.isEmpty() || sampai.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Tanggal tidak boleh kosong! (Format: yyyy-MM-dd)");
            return;
        }

        tableModelPendapatan.setRowCount(0);
        double grandTotal = 0;

        try {
            Connection con = DBConnection.getConnection();
            String sql =
                "SELECT i.noInvoice, t.nama, k.noKamar, " +
                "p.tglBayar, p.metode, p.jumlahBayar " +
                "FROM pembayaran p " +
                "JOIN invoice i ON p.idPembayaran = i.idPembayaran " +
                "JOIN reservasi r ON p.idReservasi = r.idReservasi " +
                "JOIN tamu t ON r.idTamu = t.idTamu " +
                "JOIN kamar k ON r.idKamar = k.idKamar " +
                "WHERE p.tglBayar BETWEEN ? AND ? " +
                "AND p.status = 'Paid' " +
                "ORDER BY p.tglBayar ASC";

            PreparedStatement ps = con.prepareStatement(sql);
            ps.setString(1, dari);
            ps.setString(2, sampai);
            ResultSet rs = ps.executeQuery();

            int no = 1;
            while (rs.next()) {
                double jumlahBayar = rs.getDouble("jumlahBayar");
                grandTotal += jumlahBayar;
                tableModelPendapatan.addRow(new Object[]{
                    no++,
                    rs.getString("noInvoice"),
                    rs.getString("nama"),
                    rs.getString("noKamar"),
                    rs.getString("tglBayar"),
                    rs.getString("metode"),
                    jumlahBayar
                });
            }

            lblTotalPendapatan.setText(
                "Total Pendapatan: Rp " +
                String.format("%,.0f", grandTotal));

            rs.close();
            ps.close();
            con.close();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                "Gagal memuat laporan!\n" + e.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCariPendapatanActionPerformed

